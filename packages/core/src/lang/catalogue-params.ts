// Parameter names of the catalogue's functions, for signature help (M3c). Not
// safety-critical: the prefixes and arities stay in catalogue-data.ts, and nothing here
// changes how a formula is stored.
//
// One function per line, as Microsoft's syntax line writes it:
//
//   NAME(param, [optional_param], repeated1, [repeated2], ...)  FLAGS
//
// - Names and their spelling (case, `known_y's`) are Microsoft's; a space inside a name
//   becomes `_` (`[source language]` -> `[source_language]`).
// - Optional parameters in brackets, one bracket per parameter: Microsoft's
//   `[criteria_range2, criteria2], ...` is written `[criteria_range2], [criteria2], ...`.
// - `...` is a parameter of its own and repeats the group before it: from the entry after
//   the earlier one with the same name up to its digits (`criteria1` -> `criteria2`) to
//   the entry before `...`; without such an entry, just the entry before it. Microsoft's
//   third groups (`[logical_test3], ...` in IFS) are kept where the page has them.
// - Entries after `...` are the last arguments (LAMBDA's `calculation`, MAP's `lambda`).
// - A LAMBDA argument is `lambda` (Microsoft: `lambda(row)`); its own parameters are in
//   the page's text, not here.
// - `?` flag: not confirmed by a Microsoft page (reason in the comment above the line).
// - `!arity` flag: Microsoft's brackets disagree with the arity in catalogue-data.ts, which
//   is kept (reason in the comment above the line). Without it, the required parameters
//   must number MIN and the list must reach MAX (or end in `...` for `*`); the tests and
//   `parseParams` enforce this.
// - A `#` comment above a line says where it departs from the page's syntax line.
//
// Source: Microsoft's function reference, support.microsoft.com/en-us/excel/functions/
// <name>-function, reached from "Excel functions (alphabetical)"; every page fetched and
// read on 2026-10-05. Internal functions (ANCHORARRAY, SINGLE) have no entry.
// Lines starting with `#` are comments.

